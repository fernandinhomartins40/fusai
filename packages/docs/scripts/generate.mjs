// Turns content/NN-slug.md into src/content.generated.ts, so the same Markdown is bundled by
// the API (tsup), the web (Next) and tests (Vitest) without loaders. Run: pnpm --filter @fusai/docs generate
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../content/', import.meta.url);
const out = new URL('../src/content.generated.ts', import.meta.url);

export function buildContent() {
  const pages = readdirSync(dir)
    .filter((f) => /^\d{2}-[a-z0-9-]+\.md$/.test(f))
    .sort()
    .map((file) => {
      const text = readFileSync(new URL(file, dir), 'utf8').replace(/\r\n/g, '\n');
      const title = text.match(/^# (.+)$/m)?.[1];
      const description = text.match(/^> (.+)$/m)?.[1];
      if (!title || !description) throw new Error(`${file}: needs "# Title" and "> description"`);
      const body = text.replace(/^# .+\n+> .+\n+/, '').trimEnd();
      return { slug: file.slice(3, -3), title, description, body: `${body}\n` };
    });
  return `// Generated by scripts/generate.mjs from content/*.md. Do not edit by hand.
import type { DocPage } from './types';

export const DOC_PAGES: DocPage[] = ${JSON.stringify(pages, null, 2)};
`;
}

if (
  process.argv[1] &&
  import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())
) {
  writeFileSync(out, buildContent());
  console.log('docs: content.generated.ts updated');
}
